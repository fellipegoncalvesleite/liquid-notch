import AppKit
import OSLog

private let log = Logger(subsystem: "com.fellipe.liquidnotch", category: "tray")

/// Text copied anywhere on the Mac, for the tray's Clipboard. Reads only the pasteboard's change count once a
/// second (no permission, next to no cost) and the text when it changes. Skips what password managers mark
/// concealed or transient, keeps everything in memory only, and never logs the text.
@MainActor
final class ClipboardWatcher {
    var onText: ((String) -> Void)?
    private let pasteboard = NSPasteboard.general
    private var lastCount: Int
    private var timer: Timer?

    /// The nspasteboard.org markers: concealed (passwords), transient and auto-generated content.
    static let skipped: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]

    init() { lastCount = NSPasteboard.general.changeCount }

    func start() {
        guard timer == nil else { return }
        let t = Timer(timeInterval: 1, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        t.tolerance = 0.5
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() { timer?.invalidate(); timer = nil }

    /// Puts text back on the pasteboard (a tray row clicked). Our own write isn't read back as new.
    func write(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastCount = pasteboard.changeCount
    }

    private func check() {
        let count = pasteboard.changeCount
        guard count != lastCount else { return }
        lastCount = count
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.skipped), let text = pasteboard.string(forType: .string) else { return }
        onText?(String(text.prefix(2000)))
    }
}

/// The Shortcuts app's command line: lists the user's shortcuts and runs one. Needs no permission.
enum ShortcutsCLI {
    static let tool = URL(fileURLWithPath: "/usr/bin/shortcuts")

    static func list() async -> [String] {
        guard let out = await run(["list"]) else { return [] }
        return out.split(separator: "\n").map(String.init).filter { !$0.isEmpty }
    }

    static func run(shortcut name: String) {
        Task.detached {
            let ok = await run(["run", name]) != nil
            log.notice("shortcut ran: \(ok, privacy: .public)")
        }
    }

    /// Runs the tool off the main thread; its output, or nil when it failed.
    private static func run(_ args: [String]) async -> String? {
        await withCheckedContinuation { (done: CheckedContinuation<String?, Never>) in
            let p = Process()
            p.executableURL = tool
            p.arguments = args
            let out = Pipe()
            p.standardOutput = out
            p.standardError = FileHandle.nullDevice
            p.terminationHandler = { proc in
                let data = out.fileHandleForReading.readDataToEndOfFile()
                done.resume(returning: proc.terminationStatus == 0 ? String(decoding: data, as: UTF8.self) : nil)
            }
            do { try p.run() } catch { done.resume(returning: nil) }
        }
    }
}
